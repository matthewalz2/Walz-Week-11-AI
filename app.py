from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
import numpy as np
from fastapi.staticfiles import StaticFiles
from fastapi.responses import FileResponse
import os
from xgboost import XGBRegressor

# Load the pre-trained model
model_path = os.path.join("model", "model.json")
model = XGBRegressor()
model.load_model(model_path)

# Initialize FastAPI app
app = FastAPI()

# Allow frontend (CORS)
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],  # In production, replace with your frontend URL
    allow_methods=["*"],
    allow_headers=["*"],
)

# Define request body schema
class SalesInput(BaseModel):
    sales: list[float]  # Expect exactly 6 values

# Mount the 'frontend' directory
# Create it first if it doesn't exist to prevent mounting errors
os.makedirs("frontend", exist_ok=True)
app.mount("/static", StaticFiles(directory="frontend"), name="static")

# Serve index.html at root
@app.get("/")
def serve_index():
    index_path = os.path.join("frontend", "index.html")
    if os.path.exists(index_path):
        return FileResponse(index_path)
    return {"message": "Frontend index.html not found. Please create it under frontend/index.html"}

# Define the prediction endpoint
@app.post("/predict")
async def predict(input: SalesInput):
    if len(input.sales) != 6:
        return {"error": "Exactly 6 months of sales data required."}
    data = np.array(input.sales).reshape(1, -1)
    prediction = model.predict(data)[0]
    return {"prediction": float(prediction)}